const { chromium } = require('playwright');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../dashboard');
const out = process.env.LAYOUT_ARTIFACTS || path.join(require('node:os').tmpdir(), 'dnssec-layout-review');
fs.mkdirSync(out, {recursive:true});
const server = http.createServer((req,res) => {
  const file = path.resolve(root, '.' + decodeURIComponent(new URL(req.url,'http://localhost').pathname));
  if (!file.startsWith(path.resolve(root)+path.sep)) { res.writeHead(403).end(); return; }
  const type = {'.html':'text/html; charset=utf-8','.css':'text/css','.js':'application/javascript'}[path.extname(file)];
  try { res.writeHead(200,{'Content-Type':type || 'text/plain'}); res.end(fs.readFileSync(file)); }
  catch { res.writeHead(404).end(); }
});
(async()=>{
 let browser;
 try {
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  browser=await chromium.launch({headless:true,executablePath:process.env.EDGE_PATH || path.join(process.env['ProgramFiles(x86)'] || 'C:/Program Files (x86)', 'Microsoft/Edge/Application/msedge.exe')});
  const page=await browser.newPage({viewport:{width:1366,height:768}});
  const errors=[], requests=[];
  page.on('pageerror', e=>errors.push(e.message));
  page.on('request',req=>requests.push(req.url()));
  await page.goto(`http://127.0.0.1:${server.address().port}/templates/index.html`);
  await page.screenshot({path:path.join(out,'dashboard-initial.png'),fullPage:true});
  assert.equal(await page.locator('iframe').count(),0);
  const run=async()=>{await page.locator('#run').click();await page.waitForFunction(()=>document.querySelector('#run').disabled===false);};
  const choose=async value=>{await page.locator(`input[value="${value}"]`).check();};
  await run();
  assert.equal(await page.locator('iframe').count(),2);
  assert.match(await page.locator('#secure-panel').innerText(),/Đã xác thực/);
  assert.match(await page.locator('#plain-panel').innerText(),/chưa xác thực/);
  await choose('attack');
  assert.equal(await page.locator('iframe').count(),0);
  assert.match(await page.locator('#notice').innerText(),/Lần minh họa trước/);
  await page.locator('#run').click();
  assert.equal(await page.locator('#results').getAttribute('aria-busy'),'true');
  assert.equal(await page.locator('input[value=baseline]').isDisabled(),true);
  await page.waitForFunction(()=>!document.querySelector('#run').disabled);
  assert.equal(await page.locator('#secure-panel iframe').count(),0);
  assert.equal(await page.locator('#plain-panel iframe').count(),1);
  assert.match(await page.locator('#plain-panel').innerText(),/172\.30\.53\.90/);
  assert.match(await page.locator('#secure-panel').innerText(),/SERVFAIL/);
  assert.match(await page.locator('#secure-panel').innerText(),/Không gửi HTTP/);
  assert.equal(await page.locator('iframe').getAttribute('sandbox'),'');
  const panelBottom=await page.locator('#secure-panel').evaluate(el=>el.getBoundingClientRect().bottom);
  assert.ok(panelBottom<=768, `Panels exceed viewport: ${panelBottom}`);
  await page.screenshot({path:path.join(out,'dashboard-attack.png'),fullPage:true});
  await page.getByRole('button',{name:'Xem vì sao',exact:true}).click();
  assert.equal(await page.locator('#evidence').evaluate(el=>el.open),true);
  const data=JSON.parse(await page.locator('#json').innerText());
  assert.equal(data.source,'mock');
  assert.equal(data.results.secure.http.attempted,false);
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#download').click();
  assert.match((await downloadPromise).suggestedFilename(),/^mock-.*\.json$/);
  await choose('recovery'); await run();
  assert.equal(await page.locator('iframe').count(),2);
  assert.match(await page.locator('#plain-panel').innerText(),/172\.30\.53\.80/);
  await page.locator('.review summary').click();
  await page.locator('#fixture').selectOption('dns-error');await run();
  assert.equal(await page.locator('iframe').count(),0);
  assert.match(await page.locator('#secure-panel').innerText(),/Timeout/);
  await page.locator('#fixture').selectOption('http-error');await run();
  assert.equal(await page.locator('iframe').count(),0);
  assert.match(await page.locator('#secure-panel').innerText(),/NOERROR/);
  assert.match(await page.locator('#secure-panel').innerText(),/Không tải được website/);
  await page.locator('#fixture').selectOption('infra-error');await run();
  assert.equal(await page.locator('iframe').count(),0);
  assert.match(await page.locator('#notice').innerText(),/Chưa đủ dữ liệu/);
  await page.locator('#fixture').selectOption('scenario');
  await page.locator('#run').click();await page.locator('#cancel').click();
  await page.waitForTimeout(1100);
  assert.equal(await page.locator('iframe').count(),0);
  assert.equal(await page.locator('#json').textContent(),'{}');
  assert.match(await page.locator('#secure-panel').innerText(),/Đã hủy/);
  await page.setViewportSize({width:390,height:844});
  await choose('attack');await run();
  await page.frameLocator('#plain-panel iframe').getByText('Website giả lập', {exact:false}).waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(out,'dashboard-mobile.png'),fullPage:true});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.locator('#run').click();
  assert.equal(await page.locator('.dns-path').evaluate(el=>getComputedStyle(el).animationName),'none');
  await page.locator('#cancel').click();
  assert.deepEqual(errors,[]);
  assert.ok(requests.every(url=>url.startsWith('http://127.0.0.1:') || url==='about:blank' || url==='about:srcdoc' || url.startsWith('data:')),requests.join('\n'));
  console.log(JSON.stringify({result:'PASS',checks:['initial-empty','baseline','stale-preview-removal','busy-controls','attack-plain-fake-secure-no-http','sandbox','desktop-panels-fit','evidence','mock-json-download','recovery','dns-error','http-error','infra-error','cancel-no-late-result','mobile-no-overflow','reduced-motion','no-js-errors','no-external-or-api-requests'],panelBottom,screenshots:out},null,2));
 } finally {if(browser) await browser.close();server.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
